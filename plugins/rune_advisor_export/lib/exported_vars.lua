-- The player variables posted by name, beside the ones quests and achievements test (lib/manifest.lua).
-- This file is the complete answer to "which other variables leave the client": every one is written out
-- below, and nothing else is sent. Each is a value the game shows the player somewhere: a currency balance,
-- the contents of a storage kept in variables, the collection log, a tool on the tool belt. Interface state
-- (which window tab is open, which entries are starred), world event timers and migration flags are
-- deliberately not here.
--
-- Each entry is { name, width in bits, kind }:
--   "var"     a whole player variable, 32 bits: listed only when it is one value (a balance, a count)
--   "bit"     a VarBit: a field of a bigger player variable, sent at its own width and nothing else of that
--             variable (many of the game's variables pack several unrelated fields)
--   "client"  a variable the client keeps for itself (a copy of an item's own variable), 32 bits
--   "chat"    a value the game gives only in one of its own chat messages (lib/gamechat.lua; optional chatAccess),
--             32 bits, -1 until the message has been seen
--   "ui"      a number the game shows only on its interface (lib/uiread.lua), 32 bits, -1 while it isn't shown
-- The order is the order on the wire, so the list never changes without a new plugin version, and the server
-- holds the same list (src/rune_advisor/wire_manifests/). A variable this client doesn't have, or whose kind
-- or width differs from the entry after a game update, is sent as 0 and reported absent until the next
-- version corrects the entry.
--
-- The blocks between "-- family" and "-- end family" are every variable with that name prefix in the game's
-- variable list when the plugin was built (scripts/build_exported_vars.py writes them, and the widths and
-- kinds everywhere, from the dev plugin's dump of the game's variables). A variable the game adds later is
-- not sent until a new version lists it.
--
-- A variable some quest or achievement test reads is never listed here, in a family or by hand: it already
-- travels with those tests (lib/manifest.lua), and the server passes the ones it carries whole on to the
-- planner by name. The build script leaves them out of families and refuses them as hand-written entries.

